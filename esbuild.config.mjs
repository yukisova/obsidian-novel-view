import esbuild from "esbuild";
import process from "node:process";
import { builtinModules } from "node:module";

const banner = `/*
NovelView — a novel editing mode for Markdown in Obsidian.
Generated by esbuild. Do not edit this file directly.
*/`;

const production = process.argv[2] === "production";
const watch = process.argv.includes("--watch");

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    // These are supplied by Obsidian at runtime. Sharing Obsidian's exact
    // CodeMirror instances is required for registerEditorExtension() to work.
    "@codemirror/state",
    "@codemirror/view",
    ...builtinModules,
    ...builtinModules.map((moduleName) => `node:${moduleName}`),
  ],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: production ? false : "inline",
  treeShaking: true,
  minify: production,
  legalComments: "none",
  outfile: "main.js",
});

if (watch) {
  await context.watch();
  console.log("NovelView: watching for changes...");
} else {
  await context.rebuild();
  await context.dispose();
}
